"""Deterministic synthetic wind data (DEMO / TEST ONLY - not real Elexon data).

Used so the app runs end-to-end without network access. Produces files in the
same format as ``ingest.py``. The UI shows a banner whenever this data is used.
"""
from __future__ import annotations

import csv
import json
import math
import random
from datetime import datetime, timedelta, timezone
from pathlib import Path

from ..data.models import iso

CAPACITY = 21000.0


def generate(out_dir: Path, start="2025-12-29", end="2026-02-02", seed=42, run_every_h=2):
    rng = random.Random(seed)
    t0 = datetime.fromisoformat(start).replace(tzinfo=timezone.utc)
    t1 = datetime.fromisoformat(end).replace(tzinfo=timezone.utc)
    step = timedelta(minutes=30)

    # --- "true" actuals: slow weather regimes + AR(1) noise -> logistic -> MW
    actual, t, level, noise = {}, t0, 0.0, 0.0
    n = 0
    while t < t1:
        level = 0.995 * level + rng.gauss(0, 0.09)
        noise = 0.8 * noise + rng.gauss(0, 0.05)
        diurnal = 0.15 * math.sin(2 * math.pi * (t.hour + t.minute / 60) / 24)
        x = 1.2 * level + noise + diurnal - 0.3
        actual[t] = round(CAPACITY / (1 + math.exp(-x)) * 0.85, 0)
        t += step
        n += 1

    out_dir.mkdir(parents=True, exist_ok=True)
    with (out_dir / "actuals.csv").open("w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["start_time", "generation"])
        for k in sorted(actual):
            w.writerow([iso(k), actual[k]])

    # --- forecasts: one vintage per run; error grows with horizon, correlated in time
    rows = 0
    with (out_dir / "forecasts.csv").open("w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(["publish_time", "start_time", "generation"])
        run = t0 - timedelta(hours=48)
        while run < t1:
            err = 0.0
            tgt = run + step
            while tgt <= run + timedelta(hours=48):
                if tgt in actual:
                    h = (tgt - run).total_seconds() / 3600
                    sigma = 250 + 70 * h ** 0.8
                    err = 0.92 * err + rng.gauss(0, sigma * 0.4)
                    f = min(CAPACITY, max(0.0, actual[tgt] + err - 0.01 * h * 30))
                    w.writerow([iso(run), iso(tgt), round(f, 0)])
                    rows += 1
                tgt += step
            run += timedelta(hours=run_every_h)

    (out_dir / "source.json").write_text(json.dumps({
        "source": "synthetic",
        "note": "Synthetic demo data generated by app/synthetic.py - NOT Elexon data. Run `python -m app.ingest` for real data.",
        "generated_at": iso(datetime.now(timezone.utc)),
        "seed": seed,
    }, indent=2))
    return {"actual_rows": len(actual), "forecast_rows": rows}
